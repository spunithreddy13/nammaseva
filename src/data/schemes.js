/* Helper — get scheme by id */
export const getSchemeById = (id) => SCHEMES.find(s => s.id === Number(id)) || null

/* Helper — get similar schemes */
export const getSimilarSchemes = (scheme) =>
  (scheme.similarSchemeIds || []).map(id => SCHEMES.find(s => s.id === id)).filter(Boolean)

/* Helper — check single criterion against user profile */
export const checkCriterion = (criterion, profile) => {
  if (!profile) return 'unknown'
  if (criterion.key === 'always') return criterion.match ? 'pass' : 'fail'
  const val = profile[criterion.key]
  if (!val) return 'unknown'
  if (criterion.notMatch) {
    return criterion.notMatch.includes(val) ? 'fail' : 'pass'
  }
  if (criterion.match && Array.isArray(criterion.match)) {
    return criterion.match.includes(val) ? 'pass' : 'fail'
  }
  return 'unknown'
}
